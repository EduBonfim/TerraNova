export function hasOutOfStockItems(
  products: MarketplaceOpportunity[],
  producerUsername?: string
): boolean {
  // Verifica se há produtos com estoque zerado
  if (!products || products.length === 0) return false;
  
  // Se fornecido um produtor, filtra só seus produtos
  const itemsToCheck = producerUsername
    ? products.filter((p) => p.vendedor === producerUsername)
    : products;
  
  // Retorna true se algum tem estoqueValor === 0
  return itemsToCheck.some((item) => item.estoqueValor === 0);
}

export async function checkAndCleanupExpiredAds(): Promise<void> {
  // Remove anúncios que chegaram data de esgotamento
  const now = new Date().toISOString();
  const expiredIds = MARKETPLACE_OPPORTUNITIES.filter(
    (item) => item.esgotadoEm && item.esgotadoEm < now
  ).map((item) => item.id);

  // Se houver, removeríamos do store (por enquanto não persistem)
  if (expiredIds.length > 0) {
    console.log(`Anúncios expirados removidos: ${expiredIds.join(", ")}`);
  }
}